// services/api/scripts/generate-list-relations.ts
// Regenerates src/shared/infrastructure/prisma/list-relations.generated.ts from prisma/schema/*.prisma.
// Run: npm run prisma:list-relations  (after any schema change that adds/removes a `Model[]` field)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseListRelations } from '../src/shared/infrastructure/prisma/list-relations.parser';

const root = join(__dirname, '..');
const schemaDir = join(root, 'prisma', 'schema');
const outFile = join(root, 'src', 'shared', 'infrastructure', 'prisma', 'list-relations.generated.ts');

function readSchemaText(dir: string): string {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.prisma'))
    .sort()
    .map((f) => readFileSync(join(dir, f), 'utf8'))
    .join('\n');
}

const relations = parseListRelations(readSchemaText(schemaDir));
const sorted = Object.fromEntries(
  Object.keys(relations)
    .sort()
    .map((m) => [m, Object.fromEntries(Object.entries(relations[m]).sort(([a], [b]) => a.localeCompare(b)))]),
);

const body = Object.entries(sorted)
  .map(
    ([model, fields]) =>
      `  ${model}: {\n${Object.entries(fields)
        .map(([f, t]) => `    ${f}: '${t}',\n`)
        .join('')}  },\n`,
  )
  .join('');

writeFileSync(
  outFile,
  `// services/api/src/shared/infrastructure/prisma/list-relations.generated.ts
// GENERATED by scripts/generate-list-relations.ts - do not edit. Regenerate: npm run prisma:list-relations
import type { ListRelations } from './list-relations.parser';

export const LIST_RELATIONS: ListRelations = {
${body}};
`,
);
console.log(`wrote ${outFile} (${Object.keys(sorted).length} models)`);
